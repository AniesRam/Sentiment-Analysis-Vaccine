import pandas as pd
from sklearn.feature_extraction.text import TfidfVectorizer

def clean_hashtags(tags):
    if pd.isna(tags):
        return ""
    tags = str(tags).lower()
    tags = tags.replace("[", "").replace("]", "").replace("'", "")
    tags = tags.replace(",", " ")
    return tags

df['clean_hashtags'] = df['hashtags'].apply(clean_hashtags)

# Calculate TF-IDF for 'clean_hashtags'
